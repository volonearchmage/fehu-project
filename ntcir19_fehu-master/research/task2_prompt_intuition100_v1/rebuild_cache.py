"""Rebuild omitted input/request caches offline, with byte-exact archived hashes.

No credentials, network, model calls, sampling, scoring, or authorization creation.
Existing files are verified, never replaced. --check validates generated bytes in
memory and existing files without writing anything.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import sys

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def archived_json_bytes(value, newline):
    # This is old.write's serialization, with its original Windows newline bytes
    # preserved explicitly so the same frozen hashes also reproduce on Linux.
    text = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    if newline == "CRLF":
        text = text.replace("\n", "\r\n")
    elif newline != "LF":
        raise ValueError("Unsupported archived newline convention")
    return text.encode("utf-8")


def require_hash(path, expected):
    if digest(path.read_bytes()) != expected:
        raise RuntimeError(f"Source/archive hash mismatch: {path.relative_to(ROOT)}")


def build_plan():
    selection = read(HERE / "cache_selection.json")
    manifest_path = HERE / "frozen/manifest.json"
    require_hash(manifest_path, selection["manifest_sha256"])
    manifest = read(manifest_path)
    # Validate imported code, official source inputs and historical records before
    # invoking any helper. In particular, the frozen runner is never rewritten.
    for relative, expected in manifest["source_hashes"].items():
        require_hash(ROOT / relative, expected)
    for name, expected in manifest["frozen_hashes"].items():
        path = HERE / "frozen" / name
        if name not in ("population_dev_inputs.json", "explore_inputs.json", "confirm_inputs.json"):
            require_hash(path, expected)
    spec = importlib.util.spec_from_file_location("frozen_intuition_cache_helpers", HERE / "run_experiment.py")
    runner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(runner)
    populations = {
        "explore": runner.old.cases_from_input(read(ROOT / "dataset/train/train_event_base.json")),
        "confirm": runner.old.cases_from_input(read(ROOT / "dataset/dev/dev_event_base.json")),
    }
    outputs = {"frozen/population_dev_inputs.json": populations["confirm"]}
    cases = {}
    for stage, expected_n in (("explore", 12), ("confirm", 100)):
        by_key = {(c["guid"], c["subevent_id"]): c for c in populations[stage]}
        saved = selection["selected_events"][stage]
        if len(saved) != expected_n or [c["sample_index"] for c in saved] != list(range(expected_n)):
            raise RuntimeError("Invalid archived sample indices")
        if len({(c["guid"], c["subevent_id"]) for c in saved}) != expected_n:
            raise RuntimeError("Duplicate archived selection key")
        cases[stage] = [by_key[(c["guid"], c["subevent_id"])] | {"sample_index": c["sample_index"]} for c in saved]
        outputs[f"frozen/{stage}_inputs.json"] = cases[stage]
    plans = {}
    newline = selection["json_serialization"]["newline"]
    for relative, value in outputs.items():
        data = archived_json_bytes(value, newline)
        expected = manifest["frozen_hashes"][Path(relative).name]
        if digest(data) != expected:
            raise RuntimeError(f"Generated frozen-cache bytes do not match manifest: {relative}")
        plans[relative] = data
    prompts = {v: (HERE / "frozen" / f"system_prompt_{v}.txt").read_text(encoding="utf-8") for v in runner.CONFIG["variants"]}
    for relative, metadata in selection["request_caches"].items():
        parts = Path(relative).parts
        if len(parts) != 6 or parts[0] != "run" or parts[1] not in cases or parts[2] != "cases" or parts[4] not in prompts or parts[5] != "request.json":
            raise RuntimeError("Unexpected cache path in selection manifest")
        stage, sample_index, variant = parts[1], int(parts[3]), parts[4]
        case = cases[stage][sample_index]
        result = read(HERE / Path(relative).parent / "result.json")
        if (result["guid"], result["subevent_id"], result["sample_index"], result["stage"], result["variant"]) != (
                case["guid"], case["subevent_id"], sample_index, stage, variant):
            raise RuntimeError("Archived result/cache identity mismatch")
        request = runner.payload(case, prompts[variant])
        canonical_hash = digest(runner.canonical(request).encode("utf-8"))
        if canonical_hash != result["request_sha256"] or canonical_hash != metadata["canonical_request_sha256"]:
            raise RuntimeError(f"Rebuilt request differs from archived result: {relative}")
        data = archived_json_bytes(request, newline)
        if digest(data) != metadata["file_sha256"]:
            raise RuntimeError(f"Rebuilt request bytes differ from archived request: {relative}")
        plans[relative] = data
    if len(selection["request_caches"]) != 336:
        raise RuntimeError("Expected all 336 archived request caches")
    # Validate EVERY generated/existing item before writing any missing item.
    for relative, data in plans.items():
        path = HERE / relative
        if path.exists() and path.read_bytes() != data:
            raise RuntimeError(f"Existing cache differs; refusing overwrite: {relative}")
    return plans


def rebuild(check=False):
    plans = build_plan()
    missing = [relative for relative in plans if not (HERE / relative).exists()]
    if not check:
        for relative in missing:
            path = HERE / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            # x mode protects a file created by another process after validation.
            with path.open("xb") as stream:
                stream.write(plans[relative])
                stream.flush()
                os.fsync(stream.fileno())
    print(json.dumps({"offline_only": True, "check_only": check, "validated_cache_files": len(plans),
          "validated_bytes": sum(map(len, plans.values())), "missing_before": len(missing),
          "written_files": 0 if check else len(missing), "existing_files_overwritten": 0,
          "model_calls": 0, "credentials_read": False, "new_authorization_created": False}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify all generated hashes in memory without writing caches")
    rebuild(parser.parse_args().check)
